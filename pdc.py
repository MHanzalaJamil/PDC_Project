import numpy as np
import pandas as pd
import json

# 1. Convert Galactic coordinates from degrees to radians
l = np.deg2rad(data["GLON"].to_numpy(dtype=np.float64))
b = np.deg2rad(data["GLAT"].to_numpy(dtype=np.float64))

# 2. Generate six features
X = np.column_stack([
    np.cos(b) * np.cos(l),  # X
    np.cos(b) * np.sin(l),  # Y
    np.sin(b),              # Z
    data["Plx"].to_numpy(dtype=np.float64),
    data["pmRA"].to_numpy(dtype=np.float64),
    data["pmDE"].to_numpy(dtype=np.float64)
])

# 3. Check numerical validity
assert np.isfinite(X).all(), "Found NaN or infinity!"

# 4. Calculate Z-score normalization parameters
means = X.mean(axis=0)
stds = X.std(axis=0)

assert np.all(stds > 0), "A feature has zero standard deviation!"

X_scaled = (X - means) / stds

# 5. Convert to float32
X_final = X_scaled.astype(np.float32)

# 6. Final validation
assert X_final.shape == (1094716, 6)
assert np.isfinite(X_final).all()

# 7. Save row-major binary file for C++
X_final.tofile("kmeans_input.bin")

# 8. Save preprocessing metadata
metadata = {
    "rows": int(X_final.shape[0]),
    "features": int(X_final.shape[1]),
    "dtype": "float32",
    "feature_order": ["X", "Y", "Z", "Plx", "pmRA", "pmDE"],
    "normalization": "Z-score",
    "K": 6
}

with open("kmeans_metadata.json", "w") as f:
    json.dump(metadata, f, indent=4)

np.savez(
    "kmeans_scaling.npz",
    means=means,
    stds=stds
)

print("Dataset prepared successfully!")
print("Shape:", X_final.shape)
print("Data type:", X_final.dtype)
print("Binary size:", X_final.nbytes / (1024 * 1024), "MB")
print("Feature means:", X_final.mean(axis=0))
print("Feature stds:", X_final.std(axis=0))

import numpy as np

K = 6
rng = np.random.default_rng(42)

# Select six distinct observations
indices = rng.choice(len(X_final), size=K, replace=False)

# Save initial centroids as float32
initial_centroids = X_final[indices].copy()

initial_centroids.tofile("initial_centroids.bin")

print("Initial centroids prepared!")
