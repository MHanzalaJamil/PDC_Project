# Count records for different filtering combinations
conditions = {
    "All records": pd.Series(True, index=data.index),

    "AA + AB": data["C3"].isin(["AA", "AB"]),

    "Not bad OC": data["bad_oc"] == "n",

    "AA + AB and not bad OC":
        data["C3"].isin(["AA", "AB"]) &
        (data["bad_oc"] == "n")
}

print("\n========== FILTER COMPARISON ==========")

for label, condition in conditions.items():
    print(f"\n{label}:")
    subset = data[condition]

    for threshold in [0.0, 0.5, 0.6, 0.75]:
        count = (subset["probs"] >= threshold).sum()
        print(f"  Probability >= {threshold}: {count:,}")

